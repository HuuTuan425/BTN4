CREATE DATABASE QuanLyMonHoc;
GO

USE QuanLyMonHoc;
GO

CREATE TABLE SinhVien
(
	MaSinhVien NVARCHAR(30) NOT NULL PRIMARY KEY,
	HoTen NVARCHAR(100) NOT NULL,
	NgaySinh DATE NOT NULL,
	Email NVARCHAR(150) NULL,
	SoDienThoai NVARCHAR(30) NULL,
	ChuyenNganh NVARCHAR(100) NULL
);
GO

CREATE TABLE MonHoc
(
	MaMonHoc INT NOT NULL PRIMARY KEY,
	TenMonHoc NVARCHAR(150) NOT NULL,
	SoTinChi INT NOT NULL CHECK (SoTinChi > 0),
	SoTietHoc INT NOT NULL CHECK (SoTietHoc > 0)
);
GO

CREATE TABLE BanDangKyMonHoc
(
	MaBanDangKy INT IDENTITY(10000, 1) NOT NULL PRIMARY KEY,
	MaSinhVien NVARCHAR(30) NOT NULL,
	MaMonHoc INT NOT NULL,
	ThoiGianDangKy DATETIME NOT NULL DEFAULT GETDATE(),
	CONSTRAINT FK_BanDangKy_SinhVien FOREIGN KEY (MaSinhVien)
		REFERENCES SinhVien(MaSinhVien),
	CONSTRAINT FK_BanDangKy_MonHoc FOREIGN KEY (MaMonHoc)
		REFERENCES MonHoc(MaMonHoc),
	CONSTRAINT UQ_BanDangKy_SinhVien_MonHoc UNIQUE (MaSinhVien, MaMonHoc)
);
GO
